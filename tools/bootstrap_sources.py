def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='ascii', newline='\n')

def bytes_line(data):
    return 'defb ' + ','.join(f'${b:02X}' for b in data)

def prologue(block, data, source='assets/Elite - 128k.tap', tape_sha256=REFERENCE_SHA256):
    return [
        f'; Reconstructed from {source}; no original binary is included at build time.',
        f'; TAP SHA256: {tape_sha256}',
        f'; Zero-based TAP data block {block}; payload SHA256: {sha(data)}',
        '; Generated by tools/bootstrap_sources.py. Normal builds assemble this file directly.',
        ''
    ]

def basic(data):
    lines = prologue(1, data) + ['org 0', 'BasicProgram:']
    pos = 0
    decoded = {
        5: 'SAVE "ELITE" LINE 10: VERIFY "": STOP',
        10: 'CLEAR 65535',
        15: 'BORDER 0: PAPER 0: INK 0: CLS',
        20: 'LOAD "" SCREEN$: PRINT AT 20,0;: LOAD "" CODE',
        30: 'RANDOMIZE USR 28672 ($7000)',
    }
    while pos < len(data):
        number = int.from_bytes(data[pos:pos+2], 'big')
        count = int.from_bytes(data[pos+2:pos+4], 'little')
        body = data[pos+4:pos+4+count]
        if len(body) != count or body[-1] != 13:
            raise ValueError('Invalid BASIC line')
        lines += ['', f'; {number} {decoded[number]}', f'BasicLine_{number}:',
                  f'    defb {number} >> 8,{number} & $FF',
                  f'    defw BasicLine_{number}_End - BasicLine_{number}_Body',
                  f'BasicLine_{number}_Body:']
        lines += ['    ' + bytes_line(body[i:i+16]) for i in range(0, count, 16)]
        lines += [f'BasicLine_{number}_End:']
        pos += 4 + count
    lines += ['', 'BasicProgramEnd:', f'assert BasicProgramEnd-BasicProgram = {len(data)}', '']
    write(SOURCE / 'basic.asm', '\n'.join(lines))

def screen(data):
    lines = prologue(3, data) + ['; Spectrum SCREEN$: 6144 bitmap bytes, then 768 attributes.',
                               '; Tape header says $8000; BASIC SCREEN$ overrides loading to $4000.',
                               'org 0', 'LoadingScreen:']
    for i in range(0, len(data), 16):
        if i == 6144:
            lines += ['LoadingScreenAttributes:']
        lines += ['    ' + bytes_line(data[i:i+16]) + f' ; screen offset ${i:04X}']
    lines += ['LoadingScreenEnd:', 'assert LoadingScreenAttributes-LoadingScreen = 6144',
              'assert LoadingScreenEnd-LoadingScreenAttributes = 768', '']
    write(SOURCE / 'screen.asm', '\n'.join(lines))

def graphics_regions(memory):
    """Read boundaries from the verified original LD operands, not guessed sizes."""
    def operand(address, opcode):
        if memory[address] != opcode:
            raise ValueError(f'Graphics landmark opcode changed at ${address:04X}')
        return memory[address+1] + 256*memory[address+2]

    font = operand(0x716B, 0x21)
    font_runtime = operand(0x716E, 0x11)
    font_size = operand(0x7171, 0x01)
    attributes = operand(0x7176, 0x21)
    attributes_runtime = operand(0x7179, 0x11)
    attributes_size = operand(0x717C, 0x01)
    bitmap = operand(0x743E, 0x21)
    bitmap_size = operand(0x7441, 0x01)
    bitmap_screen = operand(0x743B, 0x11)
    attributes_screen = operand(0x7446, 0x11)
    if (operand(0x7449,0x21),operand(0x744C,0x01)) != (attributes_runtime,attributes_size):
        raise ValueError('Cockpit attribute restore does not match startup copy')
    if (operand(0x8F47,0x11),operand(0x8F4A,0x21),operand(0x8F4D,0x01)) != (bitmap,bitmap_screen,bitmap_size):
        raise ValueError('Cockpit bitmap save and restore disagree')
    if (operand(0x8F52,0x11),operand(0x8F55,0x21),operand(0x8F58,0x01)) != (attributes_runtime,attributes_screen,attributes_size):
        raise ValueError('Cockpit attribute save and restore disagree')
    if operand(0xBB69,0x21) != font_runtime or memory[0xBB6C] != 0xD6:
        raise ValueError('Character lookup no longer uses the relocated font')
    first_code = memory[0xBB6D]
    glyph_height = memory[0xBBBC]
    if memory[0xBBBB] != 0x06 or glyph_height != 8 or font_size % glyph_height:
        raise ValueError('Character drawing is not a whole number of 8-row glyphs')
    if bitmap_size != 32*64 or attributes_size != 32*8:
        raise ValueError('Unexpected cockpit dimensions')
    regions = [
        dict(name='FontBitmap',file='font.asm',start=font,end=font+font_size,
             runtime=font_runtime,unit=glyph_height,first_code=first_code,
             comment='VERIFIED font: startup copies this block to FontRuntime; character lookup uses (code-FontFirstCode)*8.'),
        dict(name='CockpitAttributes',file='cockpit-attributes.asm',start=attributes,end=attributes+attributes_size,
             runtime=attributes_runtime,screen=attributes_screen,unit=32,
             comment='VERIFIED initial cockpit colours: 32 columns x 8 character rows. Copied to CockpitAttributesRuntime at startup.'),
        dict(name='CockpitBitmap',file='cockpit-bitmap.asm',start=bitmap,end=bitmap+bitmap_size,
             screen=bitmap_screen,unit=32,
             comment='VERIFIED initial cockpit bitmap: 256 x 64 pixels in Spectrum screen order. Copied to ScreenCockpitBitmap.'),
    ]
    constants = dict(FontRuntime=font_runtime,CockpitAttributesRuntime=attributes_runtime,
                     ScreenCockpitBitmap=bitmap_screen,ScreenCockpitAttributes=attributes_screen,
                     FontFirstCode=first_code,FontGlyphHeight=glyph_height)
    return regions,constants

def verified_data_regions(memory):
    """Return non-code regions supported by structure and runtime evidence."""
    if bytes(memory[0xA910:0xA917]) != b'JAMESON':
        raise ValueError('Default commander template moved or changed')
    if bytes(memory[0xD41B:0xD425]) != bytes.fromhex('DD2116A81168003EFFC9'):
        raise ValueError('104-byte active commander tape buffer reference changed')
    if bytes(memory[0x7C2D:0x7C39]) != bytes.fromhex('2110A91116A8016600EDB0C9'):
        raise ValueError('Initial commander template copy changed')
    if bytes(memory[0xD3E2:0xD3ED]) != bytes.fromhex('2116A81110A9016600EDB0'):
        raise ValueError('Commander tape working-copy update changed')
    for value in range(256):
        square = value * value
        if memory[0xBE00 + value] != square & 0xFF:
            raise ValueError('Low-byte square table changed')
        if memory[0xBF00 + value] != square >> 8:
            raise ValueError('High-byte square table changed')
    return [
        dict(name='InitialRuntimeState', file='initial-runtime-state.asm',
             start=BASE, end=0x6180, unit=39,
             comment='VERIFIED DATA: initial mutable game/object state; runtime access tracing records reads and writes here, never instruction fetches.'),
        dict(name='ShipBlueprintsAndDispatchTables', file='ship-blueprints-and-tables.asm',
             start=0x6180, end=ENTRY, unit=16,
             comment='VERIFIED DATA: structured ship geometry/blueprint records followed by in-image dispatch pointers; read at runtime and never executed.'),
        dict(name='EncodedTextData', file='encoded-text.asm',
             start=0x92B7, end=0x9965, unit=16,
             comment='VERIFIED DATA: message table of zero-terminated game text read by PrintMessage; numbering starts at 1.'),
        dict(name='TextTokenDictionary', file='text-token-dictionary.asm',
             start=0x9A9D, end=0x9E74, unit=16,
             comment='VERIFIED DATA: token dictionary used to expand screen and message text; runtime reads cover this block.'),
        dict(name='ActiveCommanderRecord', file='active-commander-initial.asm',
             start=0xA816, end=0xA87E, unit=16,
             comment='VERIFIED DATA: mutable 104-byte commander buffer used directly by ROM tape load/save; the first 102 bytes follow the supplied save map.'),
        dict(name='CommanderTemplateBuffer', file='default-commander.asm',
             start=0xA910, end=0xA976, unit=16,
             comment='VERIFIED DATA: initial 102-byte JAMESON template; copied to ActiveCommanderRecord for a new game and reused as a mutable tape-workflow copy.'),
        dict(name='SquareLookupTables', file='square-tables.asm',
             start=0xBE00, end=0xC000, unit=256,
             comment='VERIFIED DATA: 256 low bytes then 256 high bytes of n*n for n=0..255.'),
    ]

def emit_verified_data(region, memory, labels, payload, codec):
    start, end, name = region['start'], region['end'], region['name']
    lines = prologue(5, payload) + [
        f'; KNOWN DATA: ${start:04X}..${end-1:04X}, {end-start} bytes.',
        '; ' + region['comment'],
        '; Field names are given only where code or runtime evidence proves them.',
        '',
    ]
    # Text tables: one entry per zero-terminated string, with decoded text.
    entries = {}
    if name == 'EncodedTextData':
        number, address = 1, start
        while address < end:
            entries[address] = f'Message {number} (${number:02X}): ' + clip(codec.message(number), 100)
            while memory[address]:
                address += 1
            address += 1
            number += 1
    elif name == 'TextTokenDictionary':
        number, address = 0, start
        while address < end:
            codes = [f'${number + 0xA0:02X}'] if number < 0x60 else (
                [f'${number:02X}'] if number < 0x80 else [f'${number - 0x72:02X}'])
            entries[address] = (f'Token {number} (${number:02X}), PrintToken code {codes[0]}: '
                                + clip(codec.dictionary(number), 90))
            while memory[address]:
                address += 1
            address += 1
            number += 1
    pc = start
    anchor = start
    while pc < end:
        if pc in entries:
            anchor = pc
            if pc not in labels:
                lines += ['; ' + entries[pc]]
        if pc in labels:
            entry = LABELS.get(pc)
            if pc in ANNOTATIONS:
                comments = ANNOTATIONS[pc][1]
                lines += ['', '; VERIFIED: ' + renamed(comments[0])]
                lines += ['; ' + renamed(line) for line in comments[1:]]
            if entry and entry[2].strip():
                if pc not in ANNOTATIONS:
                    lines.append('')
                lines += [('; ' + renamed(line)).rstrip() for line in header_lines(entry[1], entry[2])]
            lines += [labels[pc] + ':']
            if pc in entries:
                lines += ['; ' + entries[pc]]
        if name == 'InitialRuntimeState' and labels.get(pc) == 'StationBlueprintPointer':
            # Original slot-zero pointer must match table entry zero. Emit a
            # symbol so the optional Adder layout relocates this instance too.
            if memory[pc:pc+2] != memory[TABLE_ADDRESS+1:TABLE_ADDRESS+3]:
                raise ValueError('Initial station pointer disagrees with Coriolis table entry')
            lines += ['    ; The persistent station bypasses the generic object/blueprint loader.',
                      '    defw ShipCoriolisStationBlueprint'.ljust(89) + ' ; ' + f'${pc:04X}'
                      + ('  ' + renamed(COMMENTS[pc]) if pc in COMMENTS else '')]
            pc += 2
            continue
        size = 1
        while (size < 16 and pc + size < end and (pc + size - anchor) % region['unit']
               and pc + size not in labels and pc + size not in COMMENTS and pc + size not in entries):
            size += 1
        chunk = bytes(memory[pc:pc + size])
        text = ''.join(chr(value) if 32 <= value < 127 else '.' for value in chunk)
        comment = f'${pc:04X} {text}' + ('  ' + renamed(COMMENTS[pc]) if pc in COMMENTS else '')
        lines += [f'    {bytes_line(chunk):<85} ; {comment}']
        pc += size
    lines += ['', name + 'End:', f'defc {name}Size = {name}End - {name}',
              f'assert {name}Size = {end-start}', '']
    if name == 'InitialRuntimeState':
        lines[-1:] = ['assert StationBlueprintPointer-InitialRuntimeState = $23', '']
    write(SOURCE / 'data' / region['file'], '\n'.join(lines))

def emit_graphics(region, memory, labels, payload, provenance=None):
    start,end,name = region['start'],region['end'],region['name']
    lines = (prologue(5,payload) if provenance is None else provenance) + [
        f'; KNOWN DATA: ${start:04X}..${end-1:04X}, {end-start} bytes.',
        '; ' + region['comment'],
        '; The on-tape data is initial content, NOT read-only runtime storage.',
        '; The $C000..$CFFF area is later reused by graphics buffers and temporary stack.',
    ]
    if name == 'FontBitmap':
        lines += ['; One glyph per group, top-to-bottom rows, bit 7 is the leftmost pixel.',
                  '; Includes letters, digits and custom graphic tiles in punctuation slots.',
                  '; The five zero-filled slots after code $7A are NOT part of the startup copy.']
    elif name == 'CockpitBitmap':
        lines += ['; Source offset = ((y & 7) << 8) | ((y & $38) << 2) | (x >> 3).',
                  '; Local y=0..63 maps to physical screen y=128..191.',
                  '; This address also holds saved panel state or the second view-buffer half.']
    else:
        lines += ['; Each byte: FLASH bit 7, BRIGHT bit 6, PAPER bits 5..3, INK bits 2..0.',
                  '; Rows map to character rows 16..23 of the display.']
    pc=start
    while pc<end:
        offset=pc-start
        if offset % region['unit'] == 0:
            if name == 'FontBitmap':
                code=region['first_code']+offset//region['unit']
                lines += ['', f'; Character code ${code:02X} ({code}); source ${pc:04X}.']
            elif name == 'CockpitAttributes':
                lines += ['', f'; Character row {16+offset//32}.']
            else:
                y=((offset>>8)&7)|((offset>>2)&0x38)
                lines += ['', f'; Physical screen pixel row {128+y}.']
        if pc in labels: lines += [labels[pc]+':']
        size=1
        while size<16 and pc+size<end and (pc+size-start)%region['unit'] and pc+size not in labels:
            size+=1
        lines += ['    '+bytes_line(memory[pc:pc+size])+f' ; ${pc:04X}']
        pc+=size
    lines += ['',name+'End:',f'defc {name}Size = {name}End - {name}',
              f'assert {name}End-{name} = {end-start}']
    if name == 'FontBitmap':
        lines += ['defc FontGlyphCount = FontBitmapSize / FontGlyphHeight',
                  'defc FontRuntimeEnd = FontRuntime + FontBitmapSize',
                  'assert FontRuntimeEnd = GameLoadAddress',
                  'assert FontGlyphCount * FontGlyphHeight = FontBitmapSize',
                  f'assert FontFirstCode + FontGlyphCount = ${region["first_code"]+(end-start)//region["unit"]:02X}']
    write(SOURCE/'data'/region['file'],'\n'.join(lines)+'\n')

